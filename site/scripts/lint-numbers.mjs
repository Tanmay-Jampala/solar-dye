// Fail the build if a result-like number appears in page text that was not bound from results.json.
//
// Bound numbers are rendered inside an element carrying data-key="<results.json key>" (the <Num>
// component); everything inside such an element is skipped. Attributes that carry bound numbers
// (alt text, aria-labels) must be listed in data-bound="alt aria-label" on the same element.
// Everything else (text nodes and the alt/title/aria-label/content/placeholder attributes) is
// checked for digits after removing the allow-listed names below.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(site, 'dist');

// Names and codes that contain digits but are not results.
const ALLOW = [
  /\b25BSCH01\b/g,
  /\bAM1\.5G?\b/g,
  /6-31G\*?(\(2df,p\))?/g,
  /\bB3LYP\b/g,
  /\bMMFF94\b/g,
  /\bQM9\b/g,
  /\bHOPV15\b/g,
  /\bSHA-?256\b/gi,
  /\b3D\b/g,
  /\bfig\d{2}(_\w+)?\b/gi,
  /\bPART [0-7]\b/gi,
  /\b0[0-7]\s*\/\s*0[0-7]\b/g, // part counters "03 / 07"
  /\b4-(nitroaniline|aminobenzonitrile)\b/gi,
  /\bln\s?2\b/g,
  /\b(19|20)\d{2}\b/g, // years (citations, copyright)
  /\bWOFF2\b/g,
  /\bH2O\b/g,
  /\bsrc\.\w+/g, // module names in the reproduce command
  /\b404\b/g,
  /#[0-9a-f]{3,8}\b/gi, // colours in meta theme-color
  /\b3σ/g, // the predictor's out-of-distribution warning threshold (src/lib/ridge.ts), not a result
];
const CHECKED_ATTRS = ['alt', 'title', 'aria-label', 'content', 'placeholder'];
const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);

function decode(text) {
  return text
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)));
}

function stray(text) {
  let cleaned = decode(text);
  for (const pattern of ALLOW) cleaned = cleaned.replace(pattern, ' ');
  return /\d/.test(cleaned) ? cleaned.trim().replace(/\s+/g, ' ').slice(0, 120) : null;
}

function attributes(tag) {
  const found = {};
  const body = tag.replace(/^<[\w-]+/, '').replace(/\/?>$/, '');
  for (const m of body.matchAll(/([\w:-]+)(?:\s*=\s*("([^"]*)"|'([^']*)'|([^\s"'>]+)))?/g)) {
    found[m[1].toLowerCase()] = m[3] ?? m[4] ?? m[5] ?? '';
  }
  return found;
}

function lintHtml(html) {
  const problems = [];
  // Drop blocks whose contents are code, not copy.
  html = html.replace(/<(script|style|svg|template|noscript-ignore)\b[\s\S]*?<\/\1>/gi, '');
  html = html.replace(/<!--[\s\S]*?-->/g, '');
  const tokens = html.split(/(<[^>]+>)/);
  const stack = []; // tag names; skipDepth marks a bound subtree
  let skipDepth = -1;
  for (const token of tokens) {
    if (!token) continue;
    if (token.startsWith('<')) {
      if (token.startsWith('</')) {
        stack.pop();
        if (skipDepth >= 0 && stack.length < skipDepth) skipDepth = -1;
        continue;
      }
      if (token.startsWith('<!')) continue;
      const name = token.match(/^<([\w-]+)/)?.[1]?.toLowerCase();
      if (!name) continue;
      const attrs = attributes(token);
      const bound = (attrs['data-bound'] || '').split(/\s+/);
      if (skipDepth < 0) {
        for (const attr of CHECKED_ATTRS) {
          if (attrs[attr] === undefined || bound.includes(attr)) continue;
          if (name === 'meta' && attrs.name === 'viewport') continue;
          // Absolute page and image addresses (e.g. .../parts/hf-vs-b3lyp/) are URLs, not copy.
          if (name === 'meta' && /^og:(url|image)$/.test(attrs.property || '')) continue;
          const bad = stray(attrs[attr]);
          if (bad) problems.push(`<${name} ${attr}="…">: ${bad}`);
        }
      }
      const selfClosing = token.endsWith('/>') || VOID.has(name);
      if (!selfClosing) {
        stack.push(name);
        // Bound numbers, and letter-split text (checked through its aria-label instead), are skipped.
        if (skipDepth < 0 && (attrs['data-key'] !== undefined || attrs['data-roll'] !== undefined)) skipDepth = stack.length;
      }
      continue;
    }
    if (skipDepth >= 0) continue;
    const bad = stray(token);
    if (bad) problems.push(`text: ${bad}`);
  }
  return problems;
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : full.endsWith('.html') ? [full] : [];
  });
}

if (!fs.existsSync(dist)) throw new Error('lint-numbers: site/dist not found; run astro build first');
let total = 0;
// The exported notebook is generated by the pipeline (its numbers are computed outputs), so it is
// not copy and is not linted.
for (const file of walk(dist).filter((f) => !f.includes(`${path.sep}notebook${path.sep}`))) {
  const problems = lintHtml(fs.readFileSync(file, 'utf-8'));
  for (const problem of problems) console.error(`${path.relative(dist, file)}: ${problem}`);
  total += problems.length;
}
if (total) {
  console.error(`lint-numbers: ${total} unbound number(s). Bind them with <Num k="…"/> or allow-list a name.`);
  process.exit(1);
}
console.log('lint-numbers: no unbound numbers in page text');
